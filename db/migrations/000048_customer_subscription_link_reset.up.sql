-- Момент, когда клиент сам сбросил ссылку подписки из кабинета.
--
-- Нужен для двух вещей:
--   * приглашения «подключить ещё устройство» — stateless-токены без своей
--     таблицы; выпущенные до сброса должны перестать работать, иначе друг по
--     старому приглашению получил бы уже новую ссылку;
--   * пауза между сбросами: повторный сброс отключил бы и только что заново
--     подключённые устройства самого клиента.
--
-- Строго аддитивно, как 000041: старый код читает явный список колонок и
-- новую просто не видит, поэтому откат версии не требует отката БД.

ALTER TABLE customer
    ADD COLUMN IF NOT EXISTS subscription_link_reset_at TIMESTAMPTZ NULL;
